	private void ApplyAutoGeneratedInstanceName(bool force)
	{
		string value = CreateSuggestedInstanceName();
		if (string.IsNullOrWhiteSpace(value))
		{
			return;
		}
		string text = InstanceName?.Trim() ?? string.Empty;
		if (!force && !string.IsNullOrWhiteSpace(text) && !string.Equals(text, lastAutoGeneratedInstanceName, StringComparison.OrdinalIgnoreCase))
		{
			return;
		}
		isUpdatingInstanceNameInternally = true;
		try
		{
			InstanceName = value;
			lastAutoGeneratedInstanceName = value;
		}
		finally
		{
			isUpdatingInstanceNameInternally = false;
		}
	}

	private string CreateSuggestedInstanceName()
	{
		string text = selectedMinecraftVersion?.Name?.Trim();
		if (string.IsNullOrWhiteSpace(text))
		{
			return string.Empty;
		}
		string text2 = SelectedLoaderVersion?.Version;
		switch (SelectedLoaderOption?.Kind)
		{
		case LoaderKind.Fabric:
			if (!string.IsNullOrWhiteSpace(text2))
			{
				return text + "-fabric-" + text2;
			}
			return text + "-fabric";
		case LoaderKind.Forge:
			if (!string.IsNullOrWhiteSpace(text2))
			{
				return text + "-forge-" + text2;
			}
			return text + "-forge";
		case LoaderKind.NeoForge:
			if (!string.IsNullOrWhiteSpace(text2))
			{
				return text + "-neoforge-" + text2;
			}
			return text + "-neoforge";
		case LoaderKind.Quilt:
			if (!string.IsNullOrWhiteSpace(text2))
			{
				return text + "-quilt-" + text2;
			}
			return text + "-quilt";
		default:
			return text;
		}
	}

	private bool CanInstallSelectedLoader()
	{
		LoaderKind? loaderKind = SelectedLoaderOption?.Kind;
		if (loaderKind.HasValue)
		{
			LoaderKind valueOrDefault = loaderKind.GetValueOrDefault();
			if (valueOrDefault == LoaderKind.Vanilla)
			{
				return true;
			}
			if (RequiresLoaderVersionSelection(valueOrDefault))
			{
				return !IsLoadingLoaderVersions && (!SupportsAddonLibrarySelection(valueOrDefault) || !IsLoadingAddonLibraryVersions) && string.IsNullOrWhiteSpace(LoaderVersionLoadError) && (object)SelectedLoaderVersion != null;
			}
		}
		return false;
	}

