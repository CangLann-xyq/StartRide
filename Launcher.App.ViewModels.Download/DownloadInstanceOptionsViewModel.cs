	private async Task RefreshLoaderVersionsForSelectionAsync(DownloadLoaderOption? loaderOption)
	{
		CancellationTokenSource cancellation = ReplaceLoaderRequestCancellation();
		if (!RequiresLoaderVersionSelection(loaderOption?.Kind) || selectedMinecraftVersion == null || !isActive)
		{
			ResetLoaderVersionState(cancelRequest: false);
			ReleaseLoaderCancellation(cancellation);
			return;
		}
		if (!loaderProviders.TryGetValue(loaderOption.Kind, out ILoaderProvider value) || !value.IsImplemented)
		{
			ResetLoaderVersionState(cancelRequest: false);
			ReleaseLoaderCancellation(cancellation);
			return;
		}
		string requestedVersion = selectedMinecraftVersion.Name;
		LoaderVersionLoadError = string.Empty;
		IsLoadingLoaderVersions = true;
		LoaderVersions.Clear();
		SelectedLoaderVersion = null;
		try
		{
			IReadOnlyList<LoaderVersionInfo> items = await value.GetLoaderVersionsAsync(requestedVersion, downloadSourcePreference, cancellation.Token, downloadSpeedLimitMbPerSecond);
			if (IsLoaderRequestCurrent(cancellation, loaderOption, requestedVersion))
			{
				LoaderVersions.ReplaceWith(items);
				SelectedLoaderVersion = null;
				ApplyAutoGeneratedInstanceName(force: false);
			}
		}
		catch (OperationCanceledException) when (cancellation.IsCancellationRequested)
		{
		}
		catch (Exception exception)
		{
			logger.LogWarning(exception, "Failed to load loader versions. MinecraftVersion={MinecraftVersion} Loader={Loader}", requestedVersion, loaderOption.Kind);
			if (IsLoaderRequestCurrent(cancellation, loaderOption, requestedVersion))
			{
				LoaderVersionLoadError = string.Format(Strings.Status_LoaderVersionsLoadFailedFormat, loaderOption.Title);
			}
		}
		finally
		{
			if (IsLoaderRequestCurrent(cancellation, loaderOption, requestedVersion))
			{
				IsLoadingLoaderVersions = false;
			}
			ReleaseLoaderCancellation(cancellation);
		}
	}

	private async Task RefreshAddonLibraryVersionsForSelectionAsync(DownloadLoaderOption? loaderOption)
	{
		CancellationTokenSource cancellation = ReplaceAddonRequestCancellation();
		if (!SupportsAddonLibrarySelection(loaderOption?.Kind) || selectedMinecraftVersion == null || !isActive)
		{
			ResetAddonLibraryVersionState(cancelRequest: false);
			ReleaseAddonCancellation(cancellation);
			return;
		}
		string requestedVersion = selectedMinecraftVersion.Name;
		AddonLibraryVersionLoadError = string.Empty;
		IsLoadingAddonLibraryVersions = true;
		ClearAddonLibraryVersionOptions();
		if (modrinthService == null)
		{
			IsLoadingAddonLibraryVersions = false;
			ReleaseAddonCancellation(cancellation);
			return;
		}
		try
		{
			IReadOnlyList<ModrinthVersionInfo> readOnlyList = await GetAddonLibraryVersionsAsync(loaderOption.Kind, requestedVersion, cancellation.Token);
			if (!IsAddonRequestCurrent(cancellation, loaderOption, requestedVersion))
			{
				return;
			}
			AddonLibraryVersions.Add(DownloadAddonLibraryVersionOption.None);
			bool isLatest = true;
			foreach (ModrinthVersionInfo item in readOnlyList)
			{
				AddonLibraryVersions.Add(DownloadAddonLibraryVersionOption.FromVersion(item, isLatest));
				isLatest = false;
			}
			SelectedAddonLibraryVersion = AddonLibraryVersions.FirstOrDefault((DownloadAddonLibraryVersionOption option) => option.IsInstallable) ?? AddonLibraryVersions.FirstOrDefault();
		}
		catch (OperationCanceledException) when (cancellation.IsCancellationRequested)
		{
		}
		catch (Exception exception)
		{
			logger.LogWarning(exception, "Failed to load optional loader library versions. MinecraftVersion={MinecraftVersion} Loader={Loader}", requestedVersion, loaderOption.Kind);
			if (IsAddonRequestCurrent(cancellation, loaderOption, requestedVersion))
			{
				ClearAddonLibraryVersionOptions();
				AddonLibraryVersionLoadError = GetAddonLibraryVersionLoadFailedMessage(loaderOption.Kind);
			}
		}
		finally
		{
			if (IsAddonRequestCurrent(cancellation, loaderOption, requestedVersion))
			{
				IsLoadingAddonLibraryVersions = false;
			}
			ReleaseAddonCancellation(cancellation);
		}
	}

	private async Task RefreshExistingInstanceNamesAsync(CancellationToken cancellationToken)
	{
		DownloadInstanceNameTracker downloadInstanceNameTracker = instanceNameTracker;
		downloadInstanceNameTracker.ReplaceExisting(await instanceService.GetInstancesAsync(cancellationToken));
		await CheckInstanceNameAvailabilityAsync(InstanceName, debounce: false, cancellationToken);
	}

	private void RefreshInstanceNameDuplicateMessage()
	{
		string text = InstanceName?.Trim() ?? string.Empty;
		InstanceNameDuplicateMessage = ((!string.IsNullOrWhiteSpace(text) && (instanceNameTracker.IsUnavailable(text) || string.Equals(externallyUnavailableInstanceName, text, StringComparison.OrdinalIgnoreCase))) ? Strings.Status_DuplicateInstanceName : string.Empty);
	}

	private void RequestInstanceNameAvailabilityCheck()
	{
		externallyUnavailableInstanceName = string.Empty;
		RefreshInstanceNameDuplicateMessage();
		string value = InstanceName?.Trim() ?? string.Empty;
		if (!isActive || instanceInstallNameAvailabilityService == null || string.IsNullOrEmpty(minecraftDirectory) || !VersionDirectoryName.IsSafeDirectoryName(value))
		{
			CancelNameAvailabilityRequest();
		}
		else
		{
			CheckInstanceNameAvailabilityAsync(value, debounce: true, CancellationToken.None);
		}
	}

	private async Task CheckInstanceNameAvailabilityAsync(string? instanceName, bool debounce, CancellationToken cancellationToken)
	{
		string normalizedName = instanceName?.Trim() ?? string.Empty;
		if (instanceInstallNameAvailabilityService == null || string.IsNullOrEmpty(minecraftDirectory) || !VersionDirectoryName.IsSafeDirectoryName(normalizedName))
		{
			CancelNameAvailabilityRequest();
			RefreshInstanceNameDuplicateMessage();
			return;
		}
		CancellationTokenSource requestCancellation = CancellationTokenSource.CreateLinkedTokenSource(cancellationToken);
		Interlocked.Exchange(ref nameAvailabilityCancellation, requestCancellation)?.Cancel();
		IsCheckingInstanceNameAvailability = true;
		try
		{
			if (debounce)
			{
				await Task.Delay(TimeSpan.FromMilliseconds(120.0), requestCancellation.Token);
			}
			InstanceInstallNameAvailability instanceInstallNameAvailability = await instanceInstallNameAvailabilityService.CheckAsync(minecraftDirectory, normalizedName, requestCancellation.Token);
			if (IsNameAvailabilityRequestCurrent(requestCancellation, normalizedName))
			{
				externallyUnavailableInstanceName = ((instanceInstallNameAvailability == InstanceInstallNameAvailability.Occupied) ? normalizedName : string.Empty);
				RefreshInstanceNameDuplicateMessage();
			}
		}
		catch (OperationCanceledException) when (requestCancellation.IsCancellationRequested)
		{
		}
		catch (Exception exception)
		{
			if (IsNameAvailabilityRequestCurrent(requestCancellation, normalizedName))
			{
				externallyUnavailableInstanceName = string.Empty;
				RefreshInstanceNameDuplicateMessage();
			}
			logger.LogWarning(exception, "Failed to refresh Minecraft instance name availability. InstanceName={InstanceName}", normalizedName);
		}
		finally
		{
			if (Interlocked.CompareExchange(ref nameAvailabilityCancellation, null, requestCancellation) == requestCancellation)
			{
				IsCheckingInstanceNameAvailability = false;
			}
			requestCancellation.Dispose();
		}
	}

