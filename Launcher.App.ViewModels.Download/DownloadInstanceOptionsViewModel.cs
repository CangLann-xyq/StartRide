	internal DownloadInstanceOptionsViewModel(IGameInstanceService instanceService, IEnumerable<ILoaderProvider> loaderProviders, DownloadInstanceNameTracker instanceNameTracker, IInstanceInstallNameAvailabilityService? instanceInstallNameAvailabilityService = null, IModrinthService? modrinthService = null, ILogger? logger = null)
	{
		this.instanceService = instanceService;
		this.loaderProviders = loaderProviders.ToDictionary((ILoaderProvider provider) => provider.Kind);
		this.instanceNameTracker = instanceNameTracker;
		this.instanceInstallNameAvailabilityService = instanceInstallNameAvailabilityService;
		this.modrinthService = modrinthService;
		this.logger = logger ?? NullLogger.Instance;
		LoaderOptions.Add(new DownloadLoaderOption(LoaderKind.Vanilla, Strings.Download_VanillaLoaderTitle, Strings.Download_VanillaLoaderSubtitle, string.Empty, StartRide.Core.BrandingIcons.BeamNgLogo));
		LoaderOptions.Add(new DownloadLoaderOption(LoaderKind.Fabric, Strings.Download_FabricLoaderTitle, Strings.Download_FabricLoaderSubtitle, "\ue8b7", "/Assets/Icons/block/fabric.png"));
		LoaderOptions.Add(new DownloadLoaderOption(LoaderKind.Forge, Strings.Download_ForgeLoaderTitle, Strings.Download_ForgeLoaderSubtitle, "\ue8b7", "/Assets/Icons/block/Anvil.png"));
		LoaderOptions.Add(new DownloadLoaderOption(LoaderKind.NeoForge, Strings.Download_NeoForgeLoaderTitle, Strings.Download_NeoForgeLoaderSubtitle, "\ue8b7", "/Assets/Icons/block/neo_logo.png"));
		LoaderOptions.Add(new DownloadLoaderOption(LoaderKind.Quilt, Strings.Download_QuiltLoaderTitle, Strings.Download_QuiltLoaderSubtitle, "\ue8b7", "/Assets/Icons/block/quilt_x16.png"));
		LoaderVersions.CollectionChanged += delegate
		{
			NotifyLoaderCollectionChanged();
		};
		AddonLibraryVersions.CollectionChanged += delegate
		{
			NotifyAddonCollectionChanged();
		};
		SelectedLoaderOption = LoaderOptions[0];
	}

	public async Task PrepareAsync(DownloadMinecraftVersionItem minecraftVersion, CancellationToken cancellationToken = default(CancellationToken))
	{
		isActive = true;
		selectedMinecraftVersion = minecraftVersion;
		ResetLoaderVersionState();
		ResetAddonLibraryVersionState();
		SelectedLoaderOption = LoaderOptions.First((DownloadLoaderOption option) => option.Kind == LoaderKind.Vanilla);
		ApplyAutoGeneratedInstanceName(force: true);
		await RefreshExistingInstanceNamesAsync(cancellationToken);
		NotifyStateChanged();
	}

	public void Deactivate()
	{
		isActive = false;
		selectedMinecraftVersion = null;
		CancelRequests();
		ResetLoaderVersionState();
		ResetAddonLibraryVersionState();
		lastAutoGeneratedInstanceName = string.Empty;
		NotifyStateChanged();
	}

	public void ApplyDownloadSourcePreference(DownloadSourcePreference preference)
	{
		if (downloadSourcePreference != preference)
		{
			downloadSourcePreference = preference;
			if (isActive)
			{
				RefreshLoaderVersionsForSelectionAsync(SelectedLoaderOption);
				RefreshAddonLibraryVersionsForSelectionAsync(SelectedLoaderOption);
			}
		}
	}

	public void ApplyDownloadSpeedLimit(int value)
	{
		downloadSpeedLimitMbPerSecond = Math.Max(value, 0);
	}

	public DownloadInstallRequest? CreateInstallRequest()
	{
		if (!CanInstall || selectedMinecraftVersion == null)
		{
			return null;
		}
		DownloadLoaderOption downloadLoaderOption = SelectedLoaderOption ?? LoaderOptions[0];
		string text = (string.IsNullOrWhiteSpace(InstanceName) ? selectedMinecraftVersion.Name : InstanceName.Trim());
		return new DownloadInstallRequest(selectedMinecraftVersion.Name, selectedMinecraftVersion.Type, text, downloadLoaderOption.Kind, (downloadLoaderOption.Kind == LoaderKind.Vanilla) ? null : SelectedLoaderVersion?.Version, (downloadLoaderOption.Kind != LoaderKind.Fabric) ? null : SelectedAddonLibraryVersion?.VersionId, (downloadLoaderOption.Kind != LoaderKind.Quilt) ? null : SelectedAddonLibraryVersion?.VersionId, GetSelectedLoaderDisplayName(), downloadSourcePreference, downloadSpeedLimitMbPerSecond);
	}

	public void ApplyMinecraftDirectory(string? directory)
	{
		string b = directory?.Trim() ?? string.Empty;
		if (!string.Equals(minecraftDirectory, b, StringComparison.Ordinal))
		{
			minecraftDirectory = b;
			RequestInstanceNameAvailabilityCheck();
		}
	}

	public void NotifyNameAvailabilityChanged()
	{
		RequestInstanceNameAvailabilityCheck();
	}

